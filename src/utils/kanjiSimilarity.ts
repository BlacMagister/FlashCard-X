export function getVisuallySimilarDistractors(correctAnswer: string): string[] {
  const distractors = new Set<string>();

  const chars = correctAnswer.split('');
  
  for (let i = 0; i < chars.length; i++) {
    const char = chars[i];
    if (KANJI_SIMILARITY[char]) {
      for (const similarChar of KANJI_SIMILARITY[char]) {
        const distractor = chars.map((c, index) => index === i ? similarChar : c).join('');
        if (distractor !== correctAnswer) {
          distractors.add(distractor);
        }
      }
    }
  }

  // Ensure we get unique distractors, and randomize slightly if multiple exist
  return Array.from(distractors).sort(() => Math.random() - 0.5);
}
